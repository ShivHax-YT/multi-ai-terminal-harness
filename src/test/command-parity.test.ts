// One native command list everywhere: the TS native subset, lib.rs generate_handler!, build.rs AppManifest, the capability, the
// command functions in commands.rs and the generated permission files.
import { describe, expect, it } from "vitest";

import { BROWSER_ONLY_COMMANDS, COMMANDS, type CommandName } from "@/lib/ipc/contract";

import { listFiles, readJson, readRepo } from "./repo";

const sorted = (xs: readonly string[]) => [...xs].sort();

function handlerList(): string[] {
  const lib = readRepo("src-tauri/src/lib.rs");
  const block = /generate_handler!\[([\s\S]*?)\]/.exec(lib)?.[1] ?? "";
  return [...block.matchAll(/commands::([a-z_]+)/g)].map((m) => m[1] ?? "");
}

function buildRsList(): string[] {
  const build = readRepo("src-tauri/build.rs");
  const block = /const COMMANDS: &\[&str\] = &\[([\s\S]*?)\];/.exec(build)?.[1] ?? "";
  return [...block.matchAll(/"([a-z_]+)"/g)].map((m) => m[1] ?? "");
}

function capabilityCommands(): { core: string[]; commands: string[] } {
  const cap = readJson("src-tauri/capabilities/main.json") as { permissions: string[] };
  const core = cap.permissions.filter((p) => !p.startsWith("allow-"));
  const commands = cap.permissions
    .filter((p) => p.startsWith("allow-"))
    .map((p) => p.slice("allow-".length).replaceAll("-", "_"));
  return { core, commands };
}

function commandFns(): string[] {
  const src = readRepo("src-tauri/src/commands.rs");
  return [
    ...src.matchAll(
      /#\[tauri::command\(rename_all = "snake_case"\)\]\s*pub (?:async )?fn ([a-z_]+)/g,
    ),
  ].map((m) => m[1] ?? "");
}

const demoOnly = new Set<CommandName>(BROWSER_ONLY_COMMANDS);
const native = sorted(COMMANDS.filter((command) => !demoOnly.has(command)));

describe("command parity", () => {
  it("the contract lists 39 unique commands", () => {
    expect(new Set(COMMANDS).size).toBe(COMMANDS.length);
    expect(COMMANDS.length).toBe(39);
  });

  it("keeps browser-only operations out of the native handler, manifest and capability", () => {
    expect(sorted(BROWSER_ONLY_COMMANDS)).toEqual(
      sorted([
        "choose_terminal_folder",
        "pty_write",
        "sim_approve_plan",
        "sim_run",
        "start_terminal",
      ]),
    );
    expect(sorted(handlerList())).toEqual(native);
    expect(sorted(buildRsList())).toEqual(native);
    expect(sorted(capabilityCommands().commands)).toEqual(native);
    expect(sorted(commandFns())).toEqual(native);
  });

  it("every command uses snake_case args (rename_all) and is a registered permission", () => {
    const src = readRepo("src-tauri/src/commands.rs");
    const attrs = src.match(/#\[tauri::command[^\]]*\]/g) ?? [];
    expect(attrs.length).toBe(native.length);
    for (const a of attrs) expect(a).toBe('#[tauri::command(rename_all = "snake_case")]');
    const generated = listFiles("src-tauri/permissions/autogenerated")
      .map((f) => /([a-z_]+)\.toml$/.exec(f)?.[1] ?? "")
      .filter((n) => n !== "");
    expect(sorted(generated)).toEqual(native);
  });

  it("the capability grants core:default and the app commands, nothing else", () => {
    expect(capabilityCommands().core).toEqual(["core:default"]);
  });
});
